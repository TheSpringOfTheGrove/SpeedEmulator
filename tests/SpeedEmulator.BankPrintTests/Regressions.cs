    private static void VerifyRendered(Entry entry, string variant, string text)
    {
        if (text.Contains("6228480398401725673") || text.Contains("123456789062284803")) throw new Exception("PDF仍有补造/补长的账号");
        if (variant != "distinct") return;
        if (entry.Bank.Name is "邮政" or "兴业")
            if (!text.Contains("类型辰")) throw new Exception("摘要未使用明细交易类型");
        if (entry.Bank.Name == "招行" && !text.Contains("银行摘要卯")) throw new Exception("招行银行摘要未使用独立列");
        if (entry.Bank.Name == "中行" && !text.Contains("类型辰")) throw new Exception("中行交易名称未使用明细交易名称");
        if (entry.Bank.Name == "农行" && entry.Template.Name == "农行个人纸质版" && !text.Contains("场所丁"))
            throw new Exception("农行交易网点未使用明细地点");
        if (entry.Bank.Name == "平安" && (!text.Contains("摘要甲") || !text.Contains("附言乙") || !text.Contains("场所丁")))
            throw new Exception("平安摘要/备注/网点串列");
        if (entry.Template.Name == "浦发个人电子版" && (!text.Contains("1122334455667788990") || !text.Contains("摘要甲") || !text.Contains("类型辰")))
            throw new Exception("浦发账号/摘要/交易名称串列");
    }

    private static void RenderBound(List<Entry> catalog)
    {
        foreach (var template in new[] { "浦发个人电子版", "招行个人纸质版" })
        {
            var entry = catalog.First(entry => entry.Template.Name == template);
            var records = Enumerable.Range(1, 70).Select(index =>
            {
                var row = Row(entry, "distinct");
                row.Id = row.Index = index;
                row.AccountTime = new DateTime(2026, 3, 21).AddMinutes(index);
                row.ProductBrief = $"摘要{index:000}"; row.ProductName = $"类型{index:000}";
                var column = entry.Bank.FlowColumns.FirstOrDefault(column => column.Name == "银行摘要");
                if (column?.Field is { } field) row.ExtraFields[field.Trim('[', ']')] = $"银行{index:000}";
                return row;
            }).ToArray();
            var first = Context(entry, records[0]);
            var context = new PrintRenderContext { Bank = first.Bank, BankUser = first.BankUser, Template = first.Template, Records = records };
            var directory = Path.Combine(Root, "tmp", "pdfs", "bank-print-regressions");
            Directory.CreateDirectory(directory);
            var path = Path.Combine(directory, template + "-multipage.pdf");
            var previous = Console.Out;
            try { Console.SetOut(TextWriter.Null); new ZhenchengPrintBridgeService().ExportAsync(context, path).GetAwaiter().GetResult(); }
            finally { Console.SetOut(previous); }
            using var pdf = UglyToad.PdfPig.PdfDocument.Open(path);
            if (template.StartsWith("浦发") && pdf.NumberOfPages < 2) throw new Exception("多页测试未产生多页");
            var text = string.Join("\n", pdf.GetPages().Select(page => page.Text));
            foreach (var record in records)
            {
                var marker = template.StartsWith("招行") ? $"银行{record.Index:000}" : record.ProductBrief;
                if (!text.Contains(marker)) throw new Exception("跨页缺失流水 " + marker);
            }
            Console.WriteLine($"PASS {template}: {pdf.NumberOfPages} pages, 70 source summaries preserved");
        }
    }
