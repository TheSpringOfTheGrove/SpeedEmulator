    private static void Equal(string? expected, string? actual, string label)
    {
        if (expected != actual) throw new InvalidOperationException($"{label}: expected '{expected}', got '{actual}'");
    }

    private static void VerifyValues(PrintRenderContext context, FlowRecord source, object target)
    {
        if (context.Bank.Name != "微信")
            Equal(source.OppositeAccount.Trim(), Value(target, "OppositeAccount").Trim(), "对方账号不补造、不补长、不读取未绑定旧数据");
        foreach (var field in new[] { "DepositTerm", "AgreedTerm", "NoticeType", "AppNum" })
            Equal(Value(source, field), Value(target, field), "摘要不得串入 " + field);
        Equal(Value(source, "TradeMoney"), Value(target, "TradeMoney"), "金额不变");
        Equal(Value(source, "Balance"), Value(target, "Balance"), "余额不变");
        if (context.Bank.Name is "平安" or "浦发")
            Equal(source.SerialNum, Value(target, "SerialNum"), "摘要不得覆盖流水号");
    }

