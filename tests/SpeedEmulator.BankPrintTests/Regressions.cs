    private static void TestDateGeneration(List<Entry> catalog)
    {
        var generator = typeof(FlowAutoGenerator);
        var create = generator.GetMethod("CreateRecordFromRule", Static)!;
        foreach (var bankName in new[] { "工行", "中行" })
        foreach (var value in new[] { "", "0226", "0605" })
        foreach (var fixedRule in new[] { false, true })
        {
            var bank = catalog.First(entry => entry.Bank.Name == bankName).Bank;
            var request = new FlowAutoGenerationRequest
            {
                Bank = bank, BankUser = new BankUser { Id = 990201 },
                Config = new FlowGenerationConfig(), References = [], ConstItems = []
            };
            FlowRuleBase rule = fixedRule ? new GenerateConstRule() : new GenerateReferenceRule();
            rule.AreaNum = value; rule.MinMoney = rule.MaxMoney = 100;
            rule.FloutLength = 0; rule.IncomeAttribute = "收入"; rule.ProductBrief = "测试";
            var columns = new[] { new ColumnDefinition { Name = "地区号", Field = "AreaNum" } };
            var result = (FlowRecord)create.Invoke(null, [request, rule, columns, new DateTime(2026, 3, 20), 100d])!;
            Equal(value, result.AreaNum, bankName + "/参照及固定项目地区号");
        }
        // 地区号同名但不是工行的银行，原有补号逻辑不变。
        var other = new Bank { Id = 900, Name = "测试其他银行", Type = BankTypes.Personal };
        other.FlowColumns.Add(new ColumnDefinition { Name = "地区号", Field = "AreaNum" });
        var otherRequest = new FlowAutoGenerationRequest { Bank = other, BankUser = new BankUser(), Config = new(), References = [], ConstItems = [] };
        var row = new FlowRecord { AccountTime = new DateTime(2026, 3, 20) };
        generator.GetMethod("ApplyAutoGeneratedSystemFields", Static)!.Invoke(null, [otherRequest, row]);
        if (row.AreaNum.Length != 4) throw new Exception("误改了其他银行的地区号生成规则");
    }

    private static void TestBoundFields(List<Entry> catalog)
    {
        var entry = catalog.First(entry => entry.Bank.Name == "平安");
        var row = new FlowRecord { ProductBrief = "摘要甲" };
        row.ExtraFields["ProductBrief"] = "隐藏旧值";
        var values = (Dictionary<string, object?>)Bridge.GetMethod("CreateFlowRecordPrintValues", Static)!.Invoke(null, [entry.Bank, row])!;
        Equal("摘要甲", System.Convert.ToString(values["ProductBrief"])!, "摘要2/摘要3不得覆盖主摘要");

        var bank = new Bank { Name = "招行", Type = BankTypes.Personal };
        bank.FlowColumns.Add(new ColumnDefinition { Name = "对方账号", Field = "[legacy-account]" });
        row.OppositeAccount = "隐藏旧账号"; row.ExtraFields["legacy-account"] = "1234567890";
        var context = Context(new Entry(bank, new PrintTemplate { Name = "招行个人纸质版" }), row);
        Equal("1234567890", Value(Convert(context)[0]!, "OppositeAccount"), "实际绑定扩展账号");
        row.ExtraFields["legacy-account"] = "";
        Equal("", Value(Convert(context)[0]!, "OppositeAccount"), "已清空的扩展账号不能借用隐藏属性");
    }

    private static string LocalValue(PrintRenderContext context, FlowRecord row, PrintPdfColumn column)
    {
        var type = typeof(QuestPdfPrintService).GetNestedType("BankFlowPrintDocument", BindingFlags.NonPublic)!;
        var document = Activator.CreateInstance(type, [context])!;
        return (string)type.GetMethod("GetRecordValue", Instance)!.Invoke(document, [row, column, 1])!;
    }

