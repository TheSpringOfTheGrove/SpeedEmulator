    private static void TestOperationArea(List<Entry> catalog)
    {
        var entry = catalog.First(entry => entry.Bank.Name == "工行");
        foreach (var area in new[] { "", "0605" })
        foreach (var exporter in new[] { "VendorBridge", "DefaultQuestPdfExporter", "DefaultStimulsoftExporter" })
        {
            var row = new FlowRecord { AreaNum = "4906", TradeMoney = 100, AccountTime = new DateTime(2026, 3, 20) };
            var context = Context(entry, row);
            var binding = entry.Bank.Columns.FirstOrDefault(column => column.Name == "操作地区")?.Field ?? "OperationArea";
            context.BankUser.ExtraFields[binding.Trim('[', ']')] = area;
            Equal(area, Value(Convert(context, exporter)[0]!, "AreaNum"), "打印地区必须取用户操作地区，包括空值");
            var user = new PrintUser { OperationArea = "旧值" };
            Bridge.GetMethod("ApplyTemplateSpecificBankUserFieldsFromVendorRecords", Static)!.Invoke(null, [context, user, new[] { row }]);
            Equal(area, user.OperationArea, "原生用户操作地区不能被流水4906覆盖");
            Equal(area, LocalValue(context, row, new PrintPdfColumn { Name = "地区", Field = "AreaNum" }), "本地打印操作地区");
            Equal("4906", row.AreaNum, "打印不得修改原明细地区号");
        }
    }

