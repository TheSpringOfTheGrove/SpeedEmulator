    private static void TestGuangfaExcel(Bank bank)
    {
        var service = new TableExcelService();
        var user = new BankUser { Id = 990200, BankId = bank.Id, BankName = bank.Name };
        var rows = new[] { new FlowRecord { SubAccountNum = "000123", MerchantName = "错误商户", ProductBrief = "转账存入", TradeChannel = "转账存入", TradeMoney = 123.45, Balance = 1000, AccountTime = new DateTime(2026, 9, 28, 11, 1, 40) }, new FlowRecord { SubAccountNum = "", MerchantName = "旧商户", TradeMoney = -23.45, Balance = 976.55, AccountTime = new DateTime(2026, 9, 28, 11, 2, 40) } };
        var path = Path.Combine(Output, "cgb-flow-roundtrip.xlsx");
        service.ExportFlowRecords(path, rows, bank, user);
        Check(service.ImportFlowRecords(path, bank, user));
        RenameWorkbookHeader(path, "分户序号", "商户名称");
        Check(service.ImportFlowRecords(path, bank, user));
        var rules = new FlowRuleExcelService();
        var references = new[] { new GenerateReferenceRule { SubAccountNum = "000456", MerchantName = "错误商户" } };
        var referencePath = Path.Combine(Output, "cgb-reference-roundtrip.xlsx");
        rules.ExportReferences(referencePath, references, bank.ReferenceColumns.ToArray());
        Equal("000456", rules.ImportReferences(referencePath, bank.ReferenceColumns.ToArray(), bank.Id).Single().SubAccountNum, "Excel参照序号保留前导零");
        RenameWorkbookHeader(referencePath, "分户序号", "商户名称");
        Equal("000456", rules.ImportReferences(referencePath, bank.ReferenceColumns.ToArray(), bank.Id).Single().SubAccountNum, "Excel参照商户表头别名");
        var constPath = Path.Combine(Output, "cgb-const-roundtrip.xlsx");
        rules.ExportConstItems(constPath, [new GenerateConstRule { SubAccountNum = "000789" }], bank.ConstColumns.ToArray());
        RenameWorkbookHeader(constPath, "分户序号", "商户名称");
        Equal("000789", rules.ImportConstItems(constPath, bank.ConstColumns.ToArray(), bank.Id).Single().SubAccountNum, "Excel固定项目商户表头别名");
        void Check(IReadOnlyList<FlowRecord> actual)
        {
            Equal("2", actual.Count.ToString(), "Excel条数不变");
            for (var i = 0; i < rows.Length; i++)
            {
                Equal(rows[i].SubAccountNum, actual[i].SubAccountNum, "Excel分户序号准确且不借用隐藏商户");
                Equal(rows[i].TradeMoney.ToString(), actual[i].TradeMoney.ToString(), "Excel金额不变");
                Equal(rows[i].Balance.ToString(), actual[i].Balance.ToString(), "Excel余额不变");
                Equal(rows[i].AccountTime.ToString(), actual[i].AccountTime.ToString(), "Excel日期不变");
            }
        }
    }

    private static void RenameWorkbookHeader(string path, string before, string after)
    {
        using var archive = ZipFile.Open(path, ZipArchiveMode.Update);
        var entry = archive.GetEntry("xl/sharedStrings.xml") ?? archive.GetEntry("xl/worksheets/sheet1.xml")!;
        XDocument xml;
        using (var stream = entry.Open()) xml = XDocument.Load(stream);
        var ns = (XNamespace)"http://schemas.openxmlformats.org/spreadsheetml/2006/main";
        var cells = xml.Descendants(ns + "t").Where(cell => cell.Value == before).ToArray();
        if (cells.Length != 1) throw new Exception("测试表头匹配不唯一");
        cells[0].Value = after;
        using var output = entry.Open(); output.SetLength(0); xml.Save(output);
    }

    private static void TestGuangfaPositionedImport(Bank bank)
    {
        var service = typeof(PdfImportService);
        var docType = service.GetNestedType("PdfExtractedDocument", System.Reflection.BindingFlags.NonPublic)!;
        var wordType = service.GetNestedType("PdfTextWord", System.Reflection.BindingFlags.NonPublic)!;
        var document = Activator.CreateInstance(docType)!;
        var words = (IList)docType.GetProperty("Words")!.GetValue(document)!;
        Add("商户名称", 401.5, 437.5, 118); Add("摘要", 457, 475, 118); Add("附言", 517, 535, 118);
        foreach (var y in new[] { 142d, 180d })
        {
            Add("2026-09-28", 36, 74, y); Add("11:01:", 78, 100, y); Add("40", 65, 72, y + 8);
            Add("人民币", 105, 127, y + 4); Add("+10.00", 140, 174, y + 4); Add("100.00", 198, 235, y + 4);
            Add("测试户", 270, 294, y + 4); Add("001234567890123456", 324, 392, y + 4);
            if (y == 142) Add("000123", 403, 433, y + 4);
            Add("未知新摘要", 449, 490, y + 4); Add("奖金", 518, 536, y + 4);
        }
        object?[] parameters = [bank, new BankUser(), document, null];
        if (!(bool)service.GetMethod("TryParseCgbPositionedRecords", Static)!.Invoke(null, parameters)!) throw new Exception("坐标解析失败");
        var rows = (List<FlowRecord>)parameters[3]!;
        Equal("2", rows.Count.ToString(), "坐标解析条数");
        Equal("000123", rows[0].SubAccountNum, "PDF实际商户值进入分户序号");
        Equal("", rows[1].SubAccountNum, "PDF商户空白不被摘要占用");
        foreach (var row in rows)
        {
            Equal("001234567890123456", row.OppositeAccount, "不截断账号尾数及前导零");
            Equal("未知新摘要", row.ProductBrief, "摘要不限关键词");
            Equal("奖金", row.Remark, "附言独立保留");
        }
        void Add(string text, double left, double right, double top) => words.Add(Activator.CreateInstance(wordType, [1, text, left, right, top, top + 7]));
    }

    private static void TestGuangfaSourcePdf(Bank bank, string path)
    {
        var result = new PdfImportService().ImportFlowRecordsAsync(path, bank, new BankUser { Id = 990200 }).GetAwaiter().GetResult();
        var rows = result.FlowRecords;
        Equal("390", rows.Count.ToString(), "原PDF条数");
        Equal("0", rows.Count(row => row.SubAccountNum.Length > 0).ToString(), "原PDF商户全为空");
        Equal("134", rows.Count(row => row.ProductBrief == "转账存入").ToString(), "存入摘要准确");
        Equal("220", rows.Count(row => row.ProductBrief == "转账支出").ToString(), "支出摘要准确");
        Equal("12", rows.Count(row => row.Remark == "工资").ToString(), "工资附言保留");
        Equal("12", rows.Count(row => row.Remark == "奖金").ToString(), "奖金附言保留");
        var persistedPath = Environment.GetEnvironmentVariable("SPEEDEMULATOR_CGB_COMPARE_JSON");
        if (persistedPath is not null)
        {
            var before = JsonSerializer.Deserialize<List<FlowRecord>>(File.ReadAllText(persistedPath), new JsonSerializerOptions { PropertyNameCaseInsensitive = true })!;
            var expected = before.OrderBy(row => row.AccountTime).ToArray();
            var actual = rows.OrderBy(row => row.AccountTime).ToArray();
            Equal(expected.Length.ToString(), actual.Length.ToString(), "重新解析条数不变");
            for (var i = 0; i < expected.Length; i++)
            {
                Equal(expected[i].AccountTime.ToString(), actual[i].AccountTime.ToString(), "原始交易时间不变");
                Equal(expected[i].TradeMoney.ToString(), actual[i].TradeMoney.ToString(), "原始交易金额不变");
                Equal(expected[i].Balance.ToString(), actual[i].Balance.ToString(), "原始交易余额不变");
                Equal(expected[i].OppositeAccount, actual[i].OppositeAccount, "原始对方账号不变");
            }
        }
        Console.WriteLine("PASS 真实PDF 390条：商户保持空白，134笔存入/220笔支出及12笔工资/12笔奖金附言分列正确。");
    }

    private static void RenderGuangfaMerchants(List<Entry> entries)
    {
        foreach (var entry in entries)
        {
            var rows = new[] { "TEST001", "测试商户", "" }.Select((merchant, index) => new FlowRecord
            {
                Id = index + 1, Index = index + 1, AccountTime = new DateTime(2026, 3, 20, 11, index, 0),
                SubAccountNum = merchant, MerchantName = "STALE999", ProductBrief = "字段测试", TradeChannel = "测试渠道",
                OppositeUsername = "测试户", OppositeAccount = "001234567890123456", TradeMoney = 10, Balance = 10 * (index + 1), Currency = "人民币"
            }).ToArray();
            var first = Context(entry, rows[0]);
            var context = new PrintRenderContext { Bank = entry.Bank, Template = entry.Template, BankUser = first.BankUser, Records = rows };
            var path = Path.Combine(Output, entry.Template.Name + "-merchant-test.pdf");
            var previous = Console.Out;
            try { Console.SetOut(TextWriter.Null); new ZhenchengPrintBridgeService().ExportAsync(context, path).GetAwaiter().GetResult(); }
            finally { Console.SetOut(previous); }
            using var pdf = UglyToad.PdfPig.PdfDocument.Open(path);
            var text = string.Join("\n", pdf.GetPages().Select(page => page.Text));
            if (!text.Contains("TEST001") || !text.Contains("测试商户") || text.Contains("STALE999"))
                throw new Exception(entry.Template.Name + "实际PDF未使用分户序号或仍打印旧商户");
            var imported = new PdfImportService().ImportFlowRecordsAsync(path, entry.Bank, first.BankUser).GetAwaiter().GetResult()
                .FlowRecords.OrderBy(row => row.AccountTime).ToArray();
            Equal(rows.Length.ToString(), imported.Length.ToString(), "实际PDF往返导入条数");
            for (var index = 0; index < rows.Length; index++)
            {
                Equal(rows[index].SubAccountNum, imported[index].SubAccountNum, "实际PDF往返商户对应分户序号");
                Equal(rows[index].ProductBrief, imported[index].ProductBrief, "实际PDF往返摘要不串列");
                Equal(rows[index].OppositeAccount, imported[index].OppositeAccount, "实际PDF往返账号不截断");
            }
            Console.WriteLine($"PASS 实际PDF {entry.Template.Name}: 数字/中文商户及空白均按分户序号。");
        }
    }
